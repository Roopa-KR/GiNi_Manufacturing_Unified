def from_ejson(line):
    def dec(v):
        if isinstance(v, dict):
            if set(v) == {"$date"}:
                return dt.datetime.fromisoformat(v["$date"].rstrip("Z"))
            return {k: dec(x) for k, x in v.items()}
        return v
    return {k: dec(v) for k, v in json.loads(line).items()}


# ------------------------------------------------------------------------------------------------ stores
def _get(doc, path):
    for p in path.split("."):
        if not isinstance(doc, dict) or p not in doc:
            return None
        doc = doc[p]
    return doc


def _match(doc, filt):
    for k, v in filt.items():
        if k == "$or":
            if not any(_match(doc, f) for f in v):
                return False
            continue
        val = _get(doc, k)
        if isinstance(v, dict):
            if "$exists" in v and (val is not None) != v["$exists"]:
                return False
            if "$ne" in v and val == v["$ne"]:
                return False
            if "$in" in v and val not in v["$in"]:
                return False
        elif val != v:
            return False
    return True


class MemoryStore:
    """in-process stand-in implementing the subset of MongoDB semantics the seed tools use (for tests without a server)"""
    kind = "memory"

    def __init__(self):
        self.c = collections.defaultdict(list)
        self.unique = collections.defaultdict(list)

    def ensure_unique_index(self, coll, fields, partial_exists=None):
        self.unique[coll].append((tuple(fields), partial_exists))

    def _violates(self, coll, doc):
        for fields, partial in self.unique[coll]:
            if partial and _get(doc, partial) is None:
                continue
            key = tuple(_get(doc, f) for f in fields)
            if any(tuple(_get(d, f) for f in fields) == key for d in self.c[coll] if not partial or _get(d, partial) is not None):
                return True
        return False

    def insert_only(self, coll, docs):
        """upsert {dataset_id, _seed.key} with $setOnInsert -> (inserted, matched, existing_hash_by_key)"""
        idx = {(d.get("dataset_id"), _get(d, "_seed.key")): d for d in self.c[coll] if _get(d, "_seed.key") is not None}
        ins = mat = 0; existing = {}
        for doc in docs:
            k = (doc["dataset_id"], doc["_seed"]["key"])
            if k in idx:
                mat += 1; existing[k[1]] = _get(idx[k], "_seed.content_sha256")
                continue
            new = dict(doc, _id=f"oid-{coll}-{len(self.c[coll]) + 1}")
            self.c[coll].append(new); idx[k] = new; ins += 1
        return ins, mat, existing

    def insert_one(self, coll, doc):
        if self._violates(coll, doc):
            raise ValueError("duplicate key")
        self.c[coll].append(dict(doc, _id=f"oid-{coll}-{len(self.c[coll]) + 1}"))

    def update_one(self, coll, filt, set_fields):
        for d in self.c[coll]:
            if _match(d, filt):
                for k, v in set_fields.items():
                    cur = d
                    parts = k.split(".")
                    for p in parts[:-1]:
                        cur = cur.setdefault(p, {})
                    cur[parts[-1]] = v
                return 1
        return 0

    def find(self, coll, filt=None):
        return [d for d in self.c.get(coll, []) if _match(d, filt or {})]

    def collections(self):
        return sorted(k for k, v in self.c.items() if v)


def refuse_fresh_factory(db):
    """the workbook import / seeding tools never write into a fresh-factory database (GINI_ENVIRONMENT=FRESH_FACTORY, or a database
    that already holds the fresh factory's settings or its S-FACTORY session). The synthetic demo uses its own database."""
    if (os.environ.get("GINI_ENVIRONMENT") or "").upper() == "FRESH_FACTORY":
        raise SystemExit("Refused: GINI_ENVIRONMENT=FRESH_FACTORY - the synthetic workbooks are never imported into the fresh factory. "
                         "Use the synthetic database (MONGODB_DB_NAME of the demo, GINI_ENVIRONMENT=SYNTHETIC_DEMO) to seed the demo.")
    if db.factory_settings.find_one({}, {"_id": 1}) or db.sim_sessions.find_one({"SESSION_ID": "S-FACTORY"}, {"_id": 1}):
        raise SystemExit("Refused: database %r is a fresh-factory database (factory settings / S-FACTORY present) - nothing was imported." % db.name)


class MongoStore:
    """pymongo implementation (pip install pymongo); MONGODB_URI / MONGODB_DB_NAME from the environment"""
    kind = "mongodb"

    def __init__(self, uri=None, db=None):
        from pymongo import MongoClient
        self.cli = MongoClient(uri or os.environ["MONGODB_URI"], tz_aware=False, serverSelectionTimeoutMS=int(os.environ.get("MONGODB_SERVER_SELECTION_TIMEOUT_MS", "10000")))
        self.db = self.cli[db or os.environ.get("MONGODB_DB_NAME", "gini_demo_dev")]
        refuse_fresh_factory(self.db)


    def ensure_unique_index(self, coll, fields, partial_exists=None):
        kw = dict(unique=True, name="uniq_" + "_".join(f.replace(".", "_") for f in fields))
        if partial_exists:
            kw["partialFilterExpression"] = {partial_exists: {"$exists": True}}
        self.db[coll].create_index([(f, 1) for f in fields], **kw)

    def insert_only(self, coll, docs, batch=1000):
        from pymongo import UpdateOne
        existing = {}
        keys = [d["_seed"]["key"] for d in docs]
        ds = docs[0]["dataset_id"] if docs else None
        for i in range(0, len(keys), 5000):
            for e in self.db[coll].find({"dataset_id": ds, "_seed.key": {"$in": keys[i:i + 5000]}}, {"_seed.key": 1, "_seed.content_sha256": 1}):
                existing[e["_seed"]["key"]] = e["_seed"].get("content_sha256")
        ins = mat = 0
        for i in range(0, len(docs), batch):
            ops = [UpdateOne({"dataset_id": d["dataset_id"], "_seed.key": d["_seed"]["key"]}, {"$setOnInsert": d}, upsert=True) for d in docs[i:i + batch]]
            r = self.db[coll].bulk_write(ops, ordered=False)
            ins += r.upserted_count; mat += r.matched_count
        return ins, mat, existing

    def insert_one(self, coll, doc):
        self.db[coll].insert_one(doc)

    def update_one(self, coll, filt, set_fields):
        return self.db[coll].update_one(filt, {"$set": set_fields}).modified_count

    def find(self, coll, filt=None):
        return list(self.db[coll].find(filt or {}))

    def collections(self):
        return sorted(self.db.list_collection_names())


def open_store(kind="mongodb"):
    return MemoryStore() if kind == "memory" else MongoStore()

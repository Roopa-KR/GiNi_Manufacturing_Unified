def totals(colls):
    """reconciliation totals computed identically from bundle documents or from database documents"""
    g = lambda c: colls.get(c, [])
    out = collections.OrderedDict()
    out["collection_counts"] = {c: len(v) for c, v in sorted(colls.items())}
    out["run_counts"] = {c: dict(sorted(collections.Counter(str(d.get("RUN_ID")) for d in v).items())) for c, v in sorted(colls.items()) if v and "RUN_ID" in v[0]}
    pts = collections.defaultdict(lambda: collections.defaultdict(float))
    for d in g("points_ledger"):
        if d.get("WORKER_ID"):
            pts[d["WORKER_ID"]][d.get("POINTS_CATEGORY") or "UNSPECIFIED"] += d.get("POINTS_DELTA") or 0
            pts[d["WORKER_ID"]]["TOTAL"] += d.get("POINTS_DELTA") or 0
    out["points_by_worker"] = {w: {k: round(v, 2) for k, v in sorted(c.items())} for w, c in sorted(pts.items())}
    out["points_total"] = round(sum(c["TOTAL"] for c in pts.values()), 2)
    good = collections.defaultdict(set)
    for d in g("production_events"):
        if d.get("EVENT_TYPE") == "ROUTE_COMPLETED":
            good[f"{d.get('RUN_ID')}|{d.get('ORDER_LINE_ID')}"].add(d.get("UNIT_ID"))
    out["good_tanks_by_run_order_line"] = {k: len(v) for k, v in sorted(good.items())}
    att = collections.defaultdict(float)
    for d in g("ref_worker_shift_summary"):
        att[d.get("RUN_ID")] += d.get("ATTENDED_MIN") or 0
    out["attended_min_by_run"] = {k: round(v, 1) for k, v in sorted(att.items(), key=lambda x: str(x[0]))}
    out["task_status_counts"] = dict(sorted(collections.Counter(f"{d.get('RUN_ID')}|{d.get('TASK_STATUS')}" for d in g("task_assignments")).items()))
    out["rework_loops_by_run"] = dict(sorted(collections.Counter(str(d.get("RUN_ID")) for d in g("return_movements")).items()))
    out["plan_rows_by_source"] = dict(sorted(collections.Counter(f"{d.get('RUN_ID')}|{d.get('PLAN_SOURCE')}" for d in g("worker_task_plan")).items()))
    # internal consistency of the reference outputs with the seeded events
    met = {d["WORKER_ID"]: d for d in g("ref_operator_metrics") if d.get("PERIOD") == "PERIOD_TO_HORIZON" and d.get("WORKER_ID")}
    out["operator_metrics_points_mismatch"] = sorted(w for w, d in met.items() if abs((d.get("POINTS_TOTAL") or 0) - pts.get(w, {}).get("TOTAL", 0)) > 0.011) if met else "NOT_AVAILABLE"
    lines = {d["ORDER_LINE_ID"]: d for d in g("order_lines") if d.get("RUN_ID") == "RUN-BASE"}
    out["order_line_good_qty_mismatch"] = sorted(l for l, d in lines.items() if (d.get("GOOD_COMPLETED_QTY_AT_HORIZON") or 0) != len(good.get(f"RUN-BASE|{l}", ())))
    return out



def to_ejson(doc):
    def enc(v):
        if isinstance(v, dt.datetime):
            return {"$date": v.replace(microsecond=0).isoformat() + "Z"}
        if isinstance(v, dict):
            return {k: enc(x) for k, x in v.items()}
        return v
    return json.dumps({k: enc(v) for k, v in doc.items()}, ensure_ascii=False, sort_keys=True)



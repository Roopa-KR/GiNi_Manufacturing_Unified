def kind_of(sheet, workbook):
    if sheet.startswith(GROUND_TRUTH):
        return "GROUND_TRUTH_TEST_ONLY"
    if sheet in KIND:
        return KIND[sheet]
    if "Events" in workbook or sheet in ("SHIFT_ROSTER", "ROSTER_CHANGES", "PRODUCTION_PLAN"):
        return "OPERATIONAL"
    return "ANALYTICS_REFERENCE"     # Excel analytics are reference outputs for reconciliation, not the app's calculation engine


def collection_of(sheet, kind):
    base = sheet.lower()
    return ("ref_" + base) if kind == "ANALYTICS_REFERENCE" else ("gt_" + base[3:] if kind == "GROUND_TRUTH_TEST_ONLY" else base)


def sha_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


def _canon(v):
    if isinstance(v, dt.datetime):
        return v.replace(microsecond=0).isoformat() + "Z"
    if isinstance(v, dt.date):
        return v.isoformat()
    if isinstance(v, float):
        return repr(round(v, 9))
    return v


def content_hash(fields):
    return hashlib.sha256(json.dumps({k: _canon(v) for k, v in sorted(fields.items())}, sort_keys=True, ensure_ascii=False, default=str).encode()).hexdigest()


def read_workbooks(folder, include_gt=False):
    """{sheet: dict(workbook, columns, rows=[(excel_row_number, {col: value})])} straight from the files"""
    import openpyxl
    out = {}
    for name in WORKBOOKS:
        wb = openpyxl.load_workbook(os.path.join(folder, name), read_only=True, data_only=True)
        for ws in wb.worksheets:
            if ws.title in SKIP_SHEETS or (ws.title.startswith(GROUND_TRUTH) and not include_gt):
                continue
            it = ws.iter_rows(values_only=True)
            try:
                hdr = [h for h in next(it)]
            except StopIteration:
                continue
            if not hdr or hdr[0] in (None, "NO_ROWS"):
                continue
            rows = []
            for i, r in enumerate(it, start=2):
                if r and any(v is not None for v in r):
                    rows.append((i, {h: (dt.datetime(v.year, v.month, v.day) if (isinstance(v, dt.date) and not isinstance(v, dt.datetime)) else v) for h, v in zip(hdr, r) if h}))
            out[ws.title] = dict(workbook=name, columns=[h for h in hdr if h], rows=rows)
        wb.close()
    return out


def key_fields(sheet, columns, rows):
    """business key of a sheet; checked for uniqueness, else the source row number is the key (reference / documentation sheets only)"""
    cands = []
    if sheet in COMPOSITE:
        cands.append([c for c in COMPOSITE[sheet] if c in columns])
    pk = PK.get(sheet)
    if pk and pk in columns:
        cands.append((["RUN_ID"] if "RUN_ID" in columns else []) + [pk])
    for c in cands:
        if c and len({tuple(r.get(x) for x in c) for r in rows}) == len(rows):
            return c, "BUSINESS_KEY"
    return ["_SOURCE_ROW"], "SOURCE_ROW (no unique business key - reference/documentation sheet)"


def build_documents(W, dataset_id, version):
    """{collection: dict(sheet, kind, key_fields, key_basis, docs=[...])}"""
    out = {}
    for sheet, d in W.items():
        kind = kind_of(sheet, d["workbook"])
        kf, basis = key_fields(sheet, d["columns"], [r for _, r in d["rows"]])
        docs = []
        for rownum, r in d["rows"]:
            key = "|".join(str(rownum) if k == "_SOURCE_ROW" else str(r.get(k)) for k in kf)
            doc = dict(r)
            doc["dataset_id"] = dataset_id
            doc["_origin"] = "SEED"
            doc["_seed"] = dict(key=key, sheet=sheet, workbook=d["workbook"], row=rownum, dataset_version=version, content_sha256=content_hash(r))
            docs.append(doc)
        out[collection_of(sheet, kind)] = dict(sheet=sheet, kind=kind, key_fields=kf, key_basis=basis, docs=docs)
    return out


def seeded_fields(doc):
    return {k: v for k, v in doc.items() if k not in ("_id", "dataset_id", "_origin", "_seed", "_app")}



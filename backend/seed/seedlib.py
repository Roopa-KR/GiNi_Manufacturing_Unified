"""GiNi MongoDB seed library - the three *_Final.xlsx workbooks are the only seed source.

Design (see README_SEED.md):
  * every workbook row becomes one document in a collection named after its sheet; business identifiers are kept as
    fields and combined into `_seed.key` (e.g. "RUN-BASE|PEV-B-0000001"); MongoDB `_id` is generated by the database;
  * a compound unique index {dataset_id, _seed.key} (partial: only documents that came from the seed) makes seeding
    idempotent: documents are written with $setOnInsert only, so a second seed inserts nothing and NEVER overwrites a
    document the application has changed since;
  * the content hash of every row is stored in `_seed.content_sha256`; a later workbook version whose row differs is
    reported as SEED_DRIFT and left for an explicit migration, never silently applied;
  * application activity after seeding is marked `_origin: "APP"` (new documents) or `_app.modified_at` (changes to a
    seeded document) and can be exported separately (export_app_activity.py);
  * credentials, PIN/password hashes, authentication sessions and secrets are never read from or written to Excel:
    setup_accounts.py creates them in MongoDB from environment variables at setup time.
"""
